#pragma once

#include <string>

// Apple implementation of language utilities
namespace ui::lang::apple
{

namespace // anonymous
{
// forward declare
class LanguageClientImpl;
} // namespace anonymous


///////////////////////////////////////////////////////////////////////////////
/// Abstract Class to recieve language change events
///
/// @see        ui::lang::Translator
///
///////////////////////////////////////////////////////////////////////////////
class LanguageClient
    {
    friend class LanguageClientImpl;
public:
    ///////////////////////////////////////////////////////////////////////////////
    /// Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////////
    LanguageClient ();

    ///////////////////////////////////////////////////////////////////////////////
    /// Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////////
    ~LanguageClient ();

private:
    LanguageClientImpl* m_impl; ///< Pointer to implementation

    ///////////////////////////////////////////////////////////////////////////////
    /// Implement to handle the language change
    ///
    ///////////////////////////////////////////////////////////////////////////////
    virtual void onLanguageChanged () = 0;
    };


///////////////////////////////////////////////////////////////////////////////
/// Get the current system locale string
///
/// @return     System locale string
///
/// @see        ui::lang::system()
///
///////////////////////////////////////////////////////////////////////////////
std::string systemLocale();

} // ui::lang::apple
