#pragma once

#include <QSplashScreen>

namespace ui
{
///////////////////////////////////////////////////////////////////////////////
/// Application splash screen
///
///////////////////////////////////////////////////////////////////////////////
class SplashScreen : public QSplashScreen
    {
public:
    ///////////////////////////////////////////////////////////////////////////////
    /// Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////////
    SplashScreen ();

    ///////////////////////////////////////////////////////////////////////////////
    /// Show a cotroller connection message
    ///
    /// @param[in]  controller      Name of the controller we are connecting to
    ///
    ///////////////////////////////////////////////////////////////////////////////
    void showControllerMessage (const std::string& controller);

    ///////////////////////////////////////////////////////////////////////////////
    /// Show the controllers have all finished connecting and the main window is
    /// starting to open
    ///
    ///////////////////////////////////////////////////////////////////////////////
    void showAppStartingMessage ();
    };

} // namespace ui