#pragma once

#include <control/controllers/manager.hpp>

#include <ui/clock/condition.hpp>
#include <ui/common/tiereddropdown.hpp>

#include <ui/lang.hpp>

#include <QComboBox>
#include <QFormLayout>

namespace ui::clock
{

///////////////////////////////////////////////////////////////////////////////
/// Form fields for sensor automation condition
///
///////////////////////////////////////////////////////////////////////////////
class SensorConditionForm : public ConditionForm
    {
    Q_OBJECT
public:
    ///////////////////////////////////////////////////////////////////////////////
    /// Constructor
    ///
    /// @param[in]  controllers     List of controllers
    /// @param[in]  parent          Parent widget
    ///
    ///////////////////////////////////////////////////////////////////////////////
    SensorConditionForm (control::ControllerManager& controllers, QWidget* parent);

    ///////////////////////////////////////////////////////////////////////////////
    /// Check if all fields have been filled correctly
    ///
    /// @return     True if all fields in this form have been filled correctly
    ///
    ///////////////////////////////////////////////////////////////////////////////
    virtual bool hasAcceptableInput () const override { return m_modules->currentData ().isValid (); }

    ///////////////////////////////////////////////////////////////////////////////
    /// Create the condition object for what has been entered in this form
    ///
    /// @return     Condition object
    ///
    ///////////////////////////////////////////////////////////////////////////////
    virtual control::AutomationCondition* getCondition () const override;

    ///////////////////////////////////////////////////////////////////////////////
    /// Populate the fields of this form from an existing condition
    ///
    /// @param[in]  condition       Condition to populate from
    ///
    ///////////////////////////////////////////////////////////////////////////////
    virtual void setCondition (const control::AutomationCondition& condition) override;

private:
    QFormLayout*            m_layout;
    common::TieredDropdown* m_modules;
    QComboBox*              m_ports;
    QComboBox*              m_conditions;

    ///////////////////////////////////////////////////////////////////////////////
    /// Handle the user selecting a new module
    ///
    ///////////////////////////////////////////////////////////////////////////////
    void onModuleChange ();

    ///////////////////////////////////////////////////////////////////////////////
    /// Fill the items in the port combobox
    ///
    ///////////////////////////////////////////////////////////////////////////////
    void fillPorts ();

    ///////////////////////////////////////////////////////////////////////////////
    /// Fill the sensor condition combo boxes
    ///
    ///////////////////////////////////////////////////////////////////////////////
    void fillConditions ();

    ///////////////////////////////////////////////////////////////////////////////
    /// Set all the dialog box text fields
    ///
    ///////////////////////////////////////////////////////////////////////////////
    void updateTexts ();

    ///////////////////////////////////////////////////////////////////////////////
    /// Set the form layout's text labels
    ///
    ///////////////////////////////////////////////////////////////////////////////
    void setFormLabels ();

    UILANG_ON_CHANGE (ConditionForm, updateTexts ());
    };
} // namespace ui::clock
